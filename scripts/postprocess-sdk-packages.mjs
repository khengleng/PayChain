function normalizeTests() {
  removePath(join(root, 'packages/sdk-dart/test'));
  removePath(join(root, 'packages/sdk-kotlin/src/test/kotlin/com/paychain/sdk/apis'));
  removePath(join(root, 'packages/sdk-kotlin/src/test/kotlin/com/paychain/sdk/models'));
  removePath(join(root, 'packages/sdk-dotnet/src/PayChain.Sdk.Test/Model'));
  if (existsSync(join(root, 'packages/sdk-dotnet/src/PayChain.Sdk.Test/Api'))) {
    for (const file of readdirSync(join(root, 'packages/sdk-dotnet/src/PayChain.Sdk.Test/Api'))) {
      if (file !== 'DependencyInjectionTests.cs') {
        removePath(join(root, 'packages/sdk-dotnet/src/PayChain.Sdk.Test/Api', file));
      }
    }
  }
  removePath(join(root, 'packages/sdk-php/tests/Api'));
  removePath(join(root, 'packages/sdk-php/tests/Model'));

  for (const file of curatedFiles()) writeFile(file.path, file.content);
}

function run() {
  for (const file of walk(join(root, 'packages')).filter((candidate) => textFiles.has(candidate.slice(candidate.lastIndexOf('.'))))) {
    if (file.includes('/sdk-')) scrubFile(file);
  }

  normalizeTests();

  const scanRoots = [
    join(root, 'packages/sdk-typescript'),
    join(root, 'packages/sdk-dart'),
    join(root, 'packages/sdk-kotlin'),
    join(root, 'packages/sdk-php'),
    join(root, 'packages/sdk-dotnet'),
  ];

  const residue = [];
  for (const base of scanRoots) {
    for (const file of walk(base)) {
      try {
        const content = readFileSync(file, 'utf8');
        const hasPlaceholder = file.includes('/test') || file.includes('/tests')
          ? placeholderMarkers.some((marker) => content.includes(marker))
          : false;
        if (residuePatterns.some((pattern) => pattern.test(content)) || hasPlaceholder) {
          residue.push(file.replace(root, ''));
        }
      } catch {
        // ignore binary files
      }
    }
  }

  if (residue.length > 0) {
    console.error('SDK residue remains:');
    for (const file of residue) console.error(` - ${file}`);
    process.exit(1);
  }
}

run();
