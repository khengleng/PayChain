function walk(dir, results = []) {
  if (!existsSync(dir)) return results;
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (full.includes('/.dart_tool/') || full.includes('/build/')) continue;
    if (entry.isDirectory()) walk(full, results);
    else results.push(full);
  }
  return results;
}

function writeFile(target, content) {
  if (checkOnly) return;
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, content);
}

function removePath(target) {
  if (!existsSync(target) || checkOnly) return;
  rmSync(target, { recursive: true, force: true });
}

function scrubFile(path) {
  const content = readFileSync(path, 'utf8');
  let next = content;
  for (const [from, to] of scrubReplacements) next = next.replaceAll(from, to);
  if (next !== content && !checkOnly) writeFileSync(path, next);
}

