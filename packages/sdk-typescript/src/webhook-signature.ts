import { createHmac, timingSafeEqual } from 'node:crypto';

/**
 * Webhook signature verification (§35), inlined so the SDK has NO workspace dependencies.
 *
 * Why a copy rather than an import: the SDK is consumed from outside this monorepo (PayKH is a
 * separate repo). `@paychain/security` is a `workspace:*` dependency, which resolves only here —
 * so importing it made the SDK impossible to install anywhere else. It was published nowhere and
 * private:true, meaning the integration guide told PayKH to install a package that could not be
 * installed.
 *
 * A second copy of a signature verifier is a genuine hazard: if the server's signing scheme moves
 * and this does not, verification silently starts rejecting real webhooks — or, worse, a sloppy
 * change makes it accept forgeries. webhook-signature.contract.spec.ts pins this implementation
 * against the server's real signer and fails if they ever disagree. Do not edit this file without
 * that test passing.
 *
 * Kept byte-identical in behaviour to packages/security/src/webhook-signature.ts.
 */
export interface WebhookSignatureHeaders {
  signature: string;
  timestamp: string;
}

export function verifyWebhook(
  secret: string,
  body: string,
  signatureHeader: string,
  timestamp: string,
  toleranceMs = 5 * 60 * 1000,
  nowMs?: number,
): boolean {
  const now = nowMs ?? Date.now();
  const ts = Number(timestamp);
  if (!Number.isFinite(ts)) return false;
  // Replay protection: reject stale or far-future timestamps.
  if (Math.abs(now - ts) > toleranceMs) return false;

  const expected = createHmac('sha256', secret).update(`${timestamp}.${body}`).digest('hex');
  const provided = signatureHeader.startsWith('sha256=')
    ? signatureHeader.slice('sha256='.length)
    : signatureHeader;
  const a = Buffer.from(expected, 'hex');
  const b = Buffer.from(provided, 'hex');
  if (a.length !== b.length) return false;
  return timingSafeEqual(a, b);
}
